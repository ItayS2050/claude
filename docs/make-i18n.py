LOCALES = [HE, RU, KO]


def build(loc, src):
    out = src

    # Root element carries the language and direction.
    out = out.replace('<html lang="en">',
                      f'<html lang="{loc["lang"]}" dir="{loc["dir"]}">', 1)

    # Head metadata: what search engines and social cards actually read.
    out = re.sub(r"<title>.*?</title>", f"<title>{loc['title']}</title>", out, count=1, flags=re.S)
    out = re.sub(r'(<meta name="description" content=")[^"]*(">)',
                 lambda m: m.group(1) + loc["desc"] + m.group(2), out, count=1)
    out = re.sub(r'(<meta property="og:title" content=")[^"]*(">)',
                 lambda m: m.group(1) + loc["og_title"] + m.group(2), out, count=1)
    out = re.sub(r'(<meta property="og:description" content=")[^"]*(">)',
                 lambda m: m.group(1) + loc["og_desc"] + m.group(2), out, count=1)

    # Canonical must point at this translation, not at the English original,
    # or every localised page tells Google to index the English one instead.
    out = out.replace('<link rel="canonical" href="https://get-kiko.com/">',
                      f'<link rel="canonical" href="https://get-kiko.com/{loc["path"]}/">', 1)

    # Relative asset and page links now sit one directory deeper.
    for rel in ["icon128.png", "privacy.html", "terms.html", "refund.html", "support.html"]:
        out = out.replace(f'"{rel}"', f'"../{rel}"')

    # Longest first: "Support" must not be substituted inside a sentence that
    # happens to contain it before the sentence itself gets its turn.
    #
    # Every occurrence is replaced — several strings appear both in the nav and
    # as a section heading, and they should read the same in both. Zero is the
    # error case: it means index.html has changed and this page would ship with
    # a line of English nobody on the team can proofread.
    for en, tr in sorted(loc["strings"], key=lambda p: -len(p[0])):
        if en not in out:
            raise SystemExit(
                f"[{loc['lang']}] {en!r} is not in index.html. "
                "The page has changed — update the table in make-i18n.py.")
        out = out.replace(en, tr)
    return out


def main():
    src = io.open(SRC, encoding="utf-8").read()
    for loc in LOCALES:
        d = HERE / loc["path"]
        d.mkdir(exist_ok=True)
        page = build(loc, src)
        (d / "index.html").write_text(page, encoding="utf-8")
        left = sum(1 for en, _ in loc["strings"] if en in page)
        print(f"  {loc['path']}/index.html  {len(page):,} bytes  "
              f"{len(loc['strings'])} strings  {left} untranslated")


if __name__ == "__main__":
    main()
