// harvested, so the numbers they produce are a starting point, not a truth. The
// right version of this file is real text from real users of each language.
// Replacing any block with genuine sentences makes the measurement better, and
// nothing else in the harness has to change.
//
// The mistyped halves are generated in test-quality.js from these same
// sentences, using the extension's own layout maps — which is precisely what a
// user produces by typing the sentence with the wrong layout active.

