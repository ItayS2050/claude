// Every case in test-detection.js was added after something broke, which makes
// it a regression net rather than a measurement. It cannot answer the question
// that actually matters: out of a thousand ordinary sentences somebody types,
// how many does Kiko wrongly offer to destroy?
//
// So: real sentences in each language Kiko supports. Nothing here is a trick or
// an edge case. They are the sort of thing people write in an email, a chat, a
// search box or a form — which is exactly the text Kiko must stay silent on,
// because offering to convert a correct sentence turns someone's writing into
// gibberish in front of them.
//
